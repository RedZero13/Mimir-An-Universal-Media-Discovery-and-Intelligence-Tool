"""The catalogue as a spreadsheet for manual review, and the way edits come back.

    python -m mde.catalogue.review_sheet export [path.xlsx]          # every work, one row each
    python -m mde.catalogue.review_sheet apply path.xlsx [--dry-run]  # edited cells -> seed/review-corrections.json

Edits are not written into the seed files themselves: several are regenerated by the importers and would lose them.
They go to seed/review-corrections.json, which read_seed (and demo/seed.cjs) applies after everything else, so a
reviewed value wins over an imported one. Only changed cells are recorded; the review status and notes columns are
kept there too, so the next export shows them again.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

from mde import taxonomy
from mde.catalogue.load import validate
from mde.catalogue.seedfiles import SEED_DIR, read_seed

CORRECTIONS = SEED_DIR / "review-corrections.json"
ENRICH = Path(__file__).parent.parent / "data" / "enrichment"
SITE = "https://mimir.terratalesmedia.world"
MEDIA = ["film", "series", "book", "game", "album", "online_video", "channel"]
STATUSES = ["To review", "OK", "Fix needed", "Remove"]
TERM_COLUMNS = [("Genres", "genre:"), ("Moods", "mood:"), ("Themes", "theme:")]


# ---------------------------------------------------------------- formatting cells and reading them back
def _num(v):
    if v is None or v == "":
        return None
    f = float(v)
    return int(f) if f.is_integer() else f


def fmt_list(v) -> str:
    return ", ".join(v or [])


def parse_list(s) -> list[str]:
    return [x.strip() for x in str(s or "").split(",") if x.strip()]


def fmt_credits(v) -> str:
    return "; ".join(f"{r}: {n}" for r, n, *_ in (v or []))


def parse_credits(s) -> list[list[str]]:
    out = []
    for part in str(s or "").split(";"):
        if ":" in part:
            role, name = part.split(":", 1)
            if role.strip() and name.strip():
                out.append([role.strip(), name.strip()])
    return out


def fmt_terms(terms: dict, prefix: str | None) -> str:
    keys = [k for k in terms if (k.startswith(prefix) if prefix else not any(k.startswith(p) for _, p in TERM_COLUMNS))]
    keys.sort(key=lambda k: (-terms[k], k))
    return ", ".join(f"{k[len(prefix):] if prefix else k} ({terms[k]:g})" for k in keys)


def parse_terms(s, prefix: str | None) -> dict:
    out = {}
    for part in str(s or "").split(","):
        part = part.strip()
        if not part:
            continue
        m = re.fullmatch(r"(.+?)\s*\(\s*([0-9.]+)\s*\)", part)
        key, strength = (m.group(1).strip(), float(m.group(2))) if m else (part, 1.0)
        out[(prefix or "") + key if prefix and not key.startswith(prefix) else key] = _num(strength)
    return out


def fmt_advisories(v: dict) -> str:
    lines = []
    for k, x in (v or {}).items():
        if isinstance(x, list):
            lines.append(f"{k} {x[0]:g} | {x[1]}" if len(x) > 1 and x[1] else f"{k} {x[0]:g}")
        else:
            lines.append(f"{k} {x:g}")
    return "\n".join(lines)


def parse_advisories(s) -> dict:
    out = {}
    for line in str(s or "").splitlines():
        line = line.strip()
        if not line:
            continue
        head, _, note = line.partition("|")
        bits = head.split()
        if len(bits) < 2:
            raise ValueError(f"parents' guide line {line!r}: expected 'topic strength | note'")
        key, strength = bits[0], _num(bits[1])
        out[key] = [strength, note.strip()] if note.strip() else strength
    return out


def fmt_ratings(v) -> str:
    return "\n".join(" | ".join(str(x) for x in r) for r in (v or []))


def parse_ratings(s) -> list[list[str]]:
    return [[x.strip() for x in line.split("|")] for line in str(s or "").splitlines() if line.strip()]


# Editable columns: (header, read from a work, write into a correction). A correction holds whole fields.
def _attr(name):
    return lambda w: (w.get("attributes") or {}).get(name)


EDITABLE = [
    ("Title", lambda w: w.get("title"), lambda s: str(s).strip(), "title"),
    ("Original title", lambda w: w.get("original_title"), lambda s: str(s).strip() or None, "original_title"),
    ("Year", lambda w: w.get("year"), lambda s: int(_num(s)) if _num(s) is not None else None, "year"),
    ("Language", lambda w: w.get("language"), lambda s: str(s).strip() or None, "language"),
    ("Countries", lambda w: fmt_list(w.get("countries")), parse_list, "countries"),
    ("Runtime (min)", lambda w: w.get("runtime_minutes"), _num, "runtime_minutes"),
    ("Playtime (h)", lambda w: w.get("playtime_hours"), _num, "playtime_hours"),
    ("Pages", lambda w: w.get("page_count"), _num, "page_count"),
    ("Credits (role: name; …)", lambda w: fmt_credits(w.get("credits")), parse_credits, "credits"),
    ("Franchises", lambda w: fmt_list(_attr("franchises")(w)), parse_list, "attributes.franchises"),
    ("Platforms", lambda w: fmt_list(_attr("platforms")(w)), parse_list, "attributes.platforms"),
    ("Seasons", _attr("seasons"), _num, "attributes.seasons"),
    ("Episodes", _attr("episodes"), _num, "attributes.episodes"),
    ("Release status", _attr("release_status"), lambda s: str(s).strip() or None, "attributes.release_status"),
    ("Release date", _attr("release_date"), lambda s: str(s).strip() or None, "attributes.release_date"),
    *[(label, (lambda p: lambda w: fmt_terms(w.get("terms") or {}, p))(prefix), None, f"terms:{prefix}") for label, prefix in TERM_COLUMNS],
    ("Other tags", lambda w: fmt_terms(w.get("terms") or {}, None), None, "terms:"),
    ("Content ratings (board | rating | reason)", lambda w: fmt_ratings(w.get("ratings")), parse_ratings, "ratings"),
    ("Parents' guide (topic strength | note)", lambda w: fmt_advisories(w.get("advisories")), parse_advisories, "advisories"),
    ("Summary", lambda w: w.get("summary"), lambda s: str(s).strip() or None, "summary"),
]
REVIEW = [("Review status", "status"), ("Reviewer notes", "notes")]


def _cell(v):
    return "" if v is None else v


def _same(a, b) -> bool:
    norm = lambda v: None if v in ("", None, [], {}) else v  # noqa: E731
    return norm(a) == norm(b)


# ---------------------------------------------------------------- read-only columns from the open-data enrichment
def _enrichment() -> dict:
    p = ENRICH / "wikidata.json"
    return json.loads(p.read_text())["works"] if p.exists() else {}


def _money(rows, scope=None) -> str:
    rows = [r for r in rows or [] if scope is None or r.get("scope") == scope]
    return "; ".join(f"{r.get('currency', '')} {r['amount']:,.0f}" for r in rows[:2])


def _scores(rows) -> str:
    return "; ".join(f"{r.get('publisher')} {r.get('value'):g}/{r.get('scale_max'):g}" for r in (rows or [])[:4] if r.get("value") is not None)


def _gaps(w: dict) -> str:
    t = w.get("terms") or {}
    gaps = []
    if not w.get("summary"):
        gaps.append("no written summary")
    if not any(k.startswith("genre:") for k in t):
        gaps.append("no genre")
    if not any(k.startswith("mood:") for k in t):
        gaps.append("no mood")
    if not w.get("credits"):
        gaps.append("no credits")
    if not w.get("countries"):
        gaps.append("no country")
    if not w.get("language") and w["medium"] not in ("game",):
        gaps.append("no language")
    if not (w.get("runtime_minutes") or w.get("playtime_hours") or w.get("page_count") or (w.get("attributes") or {}).get("episodes")):
        gaps.append("no length")
    if w["medium"] in ("film", "series", "game") and not w.get("advisories"):
        gaps.append("no parents' guide")
    return ", ".join(gaps)


def _source_files() -> dict[str, str]:
    out = {}
    for p in sorted(SEED_DIR.glob("*.json")):
        for w in json.loads(p.read_text()).get("works", []):
            out.setdefault(w["slug"], p.name)
    return out


# ---------------------------------------------------------------- export
def export(path: Path) -> Path:
    from openpyxl import Workbook
    from openpyxl.formatting.rule import FormulaRule
    from openpyxl.styles import Alignment, Font, PatternFill
    from openpyxl.utils import get_column_letter
    from openpyxl.worksheet.datavalidation import DataValidation

    works = read_seed()["works"]
    reviews = (json.loads(CORRECTIONS.read_text()).get("review", {}) if CORRECTIONS.exists() else {})
    wd = _enrichment()
    files = _source_files()
    tax = taxonomy.load()

    wb = Workbook()
    readme = wb.active
    readme.title = "Read me"
    ws = wb.create_sheet("Works")
    lock = PatternFill("solid", fgColor="EDEDED")
    head_fill = PatternFill("solid", fgColor="1F1D18")
    head_font = Font(bold=True, color="E8C35A")

    fixed = ["Key (do not edit)", "Seed file", "Medium", "Popularity tier", "Mimir page"]
    info = ["Wikidata", "Scores", "Budget", "Box office (worldwide)", "Awards won", "Awards nominated", "Developers", "Publishers", "Gaps"]
    headers = fixed + [h for h, *_ in EDITABLE] + [h for h, _ in REVIEW] + info
    ws.append(headers)
    for i in range(1, len(headers) + 1):
        c = ws.cell(row=1, column=i)
        c.fill, c.font = head_fill, head_font
        c.alignment = Alignment(wrap_text=True, vertical="top")
    order = {m: i for i, m in enumerate(MEDIA)}
    works.sort(key=lambda w: (order.get(w["medium"], 99), w.get("popularity_tier", 9), w["title"].lower()))
    for w in works:
        rec = wd.get(w["slug"], {})
        awards = rec.get("awards") or {}
        game = rec.get("game") or {}
        qid = (w.get("attributes") or {}).get("wikidata") or ""
        review = reviews.get(w["slug"], {})
        row = [w["slug"], files.get(w["slug"], ""), w["medium"], w.get("popularity_tier"), f"{SITE}/works/{w['slug']}/"]
        row += [_cell(get(w)) for _, get, *_ in EDITABLE]
        row += [review.get(k, "To review" if k == "status" else "") for _, k in REVIEW]
        row += [
            f"https://www.wikidata.org/wiki/{qid}" if qid else "",
            _scores(rec.get("scores")),
            _money(rec.get("budget")),
            _money(rec.get("box_office"), "worldwide"),
            len(awards.get("won", [])) or "",
            len(awards.get("nominated", [])) or "",
            fmt_list(game.get("developers")),
            fmt_list(game.get("publishers")),
            _gaps(w),
        ]
        ws.append(row)

    n = len(works) + 1
    ncol = len(headers)
    first_edit = len(fixed) + 1
    last_edit = len(fixed) + len(EDITABLE) + len(REVIEW)
    widths = {"Summary": 70, "Parents' guide (topic strength | note)": 48, "Credits (role: name; …)": 48, "Title": 34, "Other tags": 40,
              "Genres": 34, "Moods": 30, "Themes": 34, "Content ratings (board | rating | reason)": 34, "Reviewer notes": 30, "Gaps": 40,
              "Mimir page": 18, "Wikidata": 18, "Key (do not edit)": 30, "Seed file": 20}
    for i, h in enumerate(headers, 1):
        ws.column_dimensions[get_column_letter(i)].width = widths.get(h, 14)
    for col in list(range(1, first_edit)) + list(range(last_edit + 1, ncol + 1)):
        for r in range(2, n + 1):
            ws.cell(row=r, column=col).fill = lock
    ws.freeze_panes = ws.cell(row=2, column=len(fixed) + 2)   # key columns and the title stay in view
    ws.auto_filter.ref = f"A1:{get_column_letter(ncol)}{n}"
    ws.row_dimensions[1].height = 42
    status_col = get_column_letter(len(fixed) + len(EDITABLE) + 1)
    dv = DataValidation(type="list", formula1=f'"{",".join(STATUSES)}"', allow_blank=True)
    ws.add_data_validation(dv)
    dv.add(f"{status_col}2:{status_col}{n}")
    gaps_col = get_column_letter(ncol)
    def tint(cols: str, formula: str, colour: str) -> None:
        ws.conditional_formatting.add(cols, FormulaRule(formula=[formula], fill=PatternFill("solid", fgColor=colour)))

    tint(f"{gaps_col}2:{gaps_col}{n}", f"LEN({gaps_col}2)>0", "FCE8C8")
    tint(f"{status_col}2:{status_col}{n}", f'{status_col}2="Fix needed"', "F8D0D0")
    tint(f"{status_col}2:{status_col}{n}", f'{status_col}2="OK"', "D6EED8")

    # Gaps by medium
    gs = wb.create_sheet("Gaps by medium")
    kinds = ["no written summary", "no genre", "no mood", "no credits", "no country", "no language", "no length", "no parents' guide"]
    gs.append(["Medium", "Works", *kinds])
    for m in MEDIA:
        ms = [w for w in works if w["medium"] == m]
        gaps = [_gaps(w) for w in ms]
        gs.append([m, len(ms), *[sum(k in g for g in gaps) for k in kinds]])
    gs.append(["all", len(works), *[sum(k in _gaps(w) for w in works) for k in kinds]])
    for c in gs[1]:
        c.fill, c.font = head_fill, head_font
    gs.column_dimensions["A"].width = 14
    for i in range(2, len(kinds) + 3):
        gs.column_dimensions[get_column_letter(i)].width = 16

    # Tag list: the only tag names the site accepts
    ts = wb.create_sheet("Tag list")
    ts.append(["Tag (as written in the sheet)", "Column", "Label", "Meaning"])
    for key, term in tax.terms.items():
        col = next((label for label, p in TERM_COLUMNS if key.startswith(p)), "Other tags")
        shown = key.split(":", 1)[1] if col != "Other tags" else key
        ts.append([shown, col, term.label, term.definition])
    for c in ts[1]:
        c.fill, c.font = head_fill, head_font
    for col, w_ in zip("ABCD", (34, 12, 30, 90), strict=True):
        ts.column_dimensions[col].width = w_
    ts.freeze_panes = "A2"
    ts.auto_filter.ref = f"A1:D{ts.max_row}"

    readme.column_dimensions["A"].width = 120
    for line in [
        "Mimir catalogue: manual review sheet",
        f"{len(works):,} works, one row each, from the editorial seed (api/mde/seed) and the open-data enrichment.",
        "",
        "How to review",
        "• Edit only the white columns on the Works sheet. Grey columns are keys or come from open data (Wikidata etc.) and are ignored on import.",
        "• Set 'Review status' (To review, OK, Fix needed, Remove) and add 'Reviewer notes' as you go. Both are kept for the next export.",
        "• Clearing a cell removes that value. Do not change the Key column, add rows, or reorder the header row.",
        "• Filter the Gaps column to find works missing a summary, genre, mood, credits, country, language, length or parents' guide.",
        "",
        "Formats",
        "• Lists (countries, franchises, platforms): comma-separated. Countries are two-letter codes (US, GB, IN, JP …).",
        "• Language is a code (en, hi, ja …).",
        "• Credits: role: name; role: name   (roles such as director, author, creator, developer, artist, actor).",
        "• Genres / Moods / Themes / Other tags: name (strength), …  with strength from 0 to 1. Names must be in the Tag list sheet.",
        "• Content ratings: one per line, board | rating | reason   e.g.  MPA | PG-13 | Brief strong language",
        "• Parents' guide: one topic per line, topic strength | note   (0 = none, 1 = severe)",
        "   e.g.  graphic-violence 0.3 | Battle scenes, little blood.",
        "",
        "Sending it back",
        "• Return the edited file. It is applied with:  python -m mde.catalogue.review_sheet apply <file.xlsx>",
        "• Only changed cells are recorded, in api/mde/seed/review-corrections.json; nothing is applied that fails the catalogue checks.",
    ]:
        readme.append([line])
    readme["A1"].font = Font(bold=True, size=14)
    for r in (4, 10, 19):
        readme.cell(row=r, column=1).font = Font(bold=True)
    wb.move_sheet("Works", offset=-1)
    wb.active = 0
    path.parent.mkdir(parents=True, exist_ok=True)
    wb.save(path)
    return path


# ---------------------------------------------------------------- apply
def apply(path: Path, dry_run: bool = False) -> dict:
    from openpyxl import load_workbook

    tax = taxonomy.load()
    works = {w["slug"]: w for w in read_seed()["works"]}
    ws = load_workbook(path, read_only=True, data_only=True)["Works"]
    rows = ws.iter_rows(values_only=True)
    headers = list(next(rows))
    col = {h: i for i, h in enumerate(headers)}
    for h in ["Key (do not edit)", *[e[0] for e in EDITABLE], *[r[0] for r in REVIEW]]:
        if h not in col:
            raise SystemExit(f"column {h!r} is missing: was the header row changed?")
    data = json.loads(CORRECTIONS.read_text()) if CORRECTIONS.exists() else {}
    fixes, reviews = data.setdefault("corrections", {}), data.setdefault("review", {})
    changed, errors = 0, []
    for r in rows:
        slug = r[col["Key (do not edit)"]]
        if not slug:
            continue
        w = works.get(slug)
        if w is None:
            errors.append(f"{slug}: not in the catalogue (rows cannot be added here)")
            continue
        patch = {}
        try:
            terms_new, terms_touched = {}, False
            for header, get, parse, field in EDITABLE:
                cell = r[col[header]]
                if field.startswith("terms:"):
                    prefix = field.split(":", 1)[1] or None
                    if not _same(_cell(get(w)), _cell(cell)):
                        terms_touched = True
                    terms_new.update(parse_terms(cell, prefix))
                    continue
                if _same(_cell(get(w)), _cell(cell)):
                    continue
                patch[field] = parse(cell if cell is not None else "")
            if terms_touched:
                unknown = [k for k in terms_new if k not in tax.terms]
                if unknown:
                    raise ValueError(f"unknown tags {unknown[:4]} (see the Tag list sheet)")
                patch["terms"] = terms_new
        except (ValueError, TypeError) as e:
            errors.append(f"{slug}: {e}")
            continue
        if patch:
            fixes[slug] = {**fixes.get(slug, {}), **patch}
            changed += 1
        review = {k: r[col[h]] for h, k in REVIEW if r[col[h]] not in (None, "")}
        if review and review != {"status": "To review"}:
            reviews[slug] = review
    # Nothing goes in that the catalogue checks reject.
    if changed:
        trial = read_seed(corrections=data)
        problems = validate(trial, tax)
        if problems:
            errors += [f"check: {p}" for p in problems[:30]]
    report = {"changed_works": changed, "reviewed": len(reviews), "errors": errors}
    if not dry_run and not [e for e in errors if e.startswith("check:")]:
        about = "Edits from the manual review sheet (python -m mde.catalogue.review_sheet). Applied after every other seed file."
        out = {"about": about, "corrections": dict(sorted(fixes.items())), "review": dict(sorted(reviews.items()))}
        CORRECTIONS.write_text(json.dumps(out, ensure_ascii=False, indent=1) + "\n")
    return report


def main() -> None:
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    e = sub.add_parser("export")
    e.add_argument("path", nargs="?", default="audit-out/mimir-catalogue-review.xlsx")
    a = sub.add_parser("apply")
    a.add_argument("path")
    a.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()
    if args.cmd == "export":
        print(f"wrote {export(Path(args.path))}")
    else:
        rep = apply(Path(args.path), args.dry_run)
        print(json.dumps(rep, indent=1, ensure_ascii=False))
        sys.exit(1 if rep["errors"] else 0)


if __name__ == "__main__":
    main()
